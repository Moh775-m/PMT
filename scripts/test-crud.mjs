// Automated verification script for all 5 CRUD operations
// Tests: 1. Read List, 2. Create, 3. Read Single, 4. Update, 5. Delete

// 1. Setup in-memory localStorage polyfill for Node.js test environment
const storage = new Map();
globalThis.localStorage = {
  getItem: (key) => storage.get(key) || null,
  setItem: (key, value) => storage.set(key, String(value)),
  removeItem: (key) => storage.delete(key),
  clear: () => storage.clear(),
};

async function runTests() {
  console.log('=============================================');
  console.log('   VERIFYING POST MANAGEMENT CRUD OPERATIONS ');
  console.log('=============================================\n');

  const {
    getPosts,
    createPost,
    getPostById,
    updatePost,
    deletePost,
    resetMockPosts,
  } = await import('../src/services/postsService.ts');

  let passCount = 0;
  const totalTests = 5;

  // Reset to initial mock posts
  resetMockPosts();

  // OPERATION 1: READ LIST
  console.log('Test 1: Read List (getPosts)...');
  const initialPosts = await getPosts();
  console.log(`  Initial posts loaded: ${initialPosts.length}`);
  if (initialPosts.length === 6) {
    console.log('  ✓ Initial 6 mock posts retrieved successfully.');
    passCount++;
  } else {
    throw new Error(`Expected 6 initial posts, got ${initialPosts.length}`);
  }

  // OPERATION 2: CREATE POST
  console.log('\nTest 2: Create Post (createPost)...');
  const newPostInput = {
    title: 'Verification Test: Automated CI/CD Pipelines in 2026',
    category: 'DevOps',
    author: 'Test Engineer',
    status: 'Published',
    imageUrl: 'https://images.unsplash.com/photo-1618401471353-b98aedd04e11',
    excerpt: 'Verifying seamless post creation with automated test assertions.',
    content: 'This post was generated by the automated test suite to verify full CRUD lifecycle.',
  };

  const createdPost = await createPost(newPostInput);
  console.log(`  Created Post ID: ${createdPost.id}`);
  console.log(`  Created Title: "${createdPost.title}"`);
  console.log(`  Status: ${createdPost.status}, Date: ${createdPost.date}`);

  const postsAfterCreate = await getPosts();
  if (
    createdPost.id &&
    createdPost.title === newPostInput.title &&
    postsAfterCreate.length === 7 &&
    postsAfterCreate[0].id === createdPost.id
  ) {
    console.log('  ✓ Post created and persisted to list successfully.');
    passCount++;
  } else {
    throw new Error('Failed to create or prepend post to storage.');
  }

  // OPERATION 3: READ SINGLE POST
  console.log('\nTest 3: Read Single Post (getPostById)...');
  const fetchedPost = await getPostById(createdPost.id);
  if (
    fetchedPost &&
    fetchedPost.id === createdPost.id &&
    fetchedPost.title === newPostInput.title &&
    fetchedPost.category === 'DevOps'
  ) {
    console.log(`  Retrieved: "${fetchedPost.title}" (Category: ${fetchedPost.category})`);
    console.log('  ✓ Read single post by ID matches exact created record.');
    passCount++;
  } else {
    throw new Error(`Failed to fetch post by ID ${createdPost.id}`);
  }

  // OPERATION 4: UPDATE POST
  console.log('\nTest 4: Update Post (updatePost)...');
  const updatedData = {
    title: 'Verification Test: Automated CI/CD Pipelines [UPDATED]',
    status: 'Draft',
    excerpt: 'Updated summary excerpt after modification.',
  };

  const updatedPost = await updatePost(createdPost.id, updatedData);
  const reFetchedPost = await getPostById(createdPost.id);

  if (
    updatedPost.title === updatedData.title &&
    updatedPost.status === 'Draft' &&
    reFetchedPost?.title === updatedData.title &&
    reFetchedPost?.status === 'Draft'
  ) {
    console.log(`  Updated Title: "${reFetchedPost.title}"`);
    console.log(`  Updated Status: ${reFetchedPost.status}`);
    console.log('  ✓ Post successfully updated and changes persisted.');
    passCount++;
  } else {
    throw new Error('Failed to update post.');
  }

  // OPERATION 5: DELETE POST
  console.log('\nTest 5: Delete Post (deletePost)...');
  const deleteResult = await deletePost(createdPost.id);
  const postAfterDelete = await getPostById(createdPost.id);
  const finalPosts = await getPosts();

  if (deleteResult === true && postAfterDelete === null && finalPosts.length === 6) {
    console.log(`  Delete confirmation returned: ${deleteResult}`);
    console.log(`  Post count restored to: ${finalPosts.length}`);
    console.log(`  Post query after deletion: ${postAfterDelete}`);
    console.log('  ✓ Post successfully deleted.');
    passCount++;
  } else {
    throw new Error('Failed to delete post.');
  }

  console.log('\n=============================================');
  console.log(`   ALL ${passCount}/${totalTests} CRUD OPERATIONS PASSED WITH 0 ERRORS! `);
  console.log('=============================================\n');
}

runTests().catch((err) => {
  console.error('\n❌ Test failed:', err);
  process.exit(1);
});
